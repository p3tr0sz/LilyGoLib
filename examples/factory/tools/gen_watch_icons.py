"""Draws the watch Clock icons and writes them as LVGL A8 images.

A8 images hold only coverage, so the UI tints them with image_recolor.
Run: python3 tools/gen_watch_icons.py   (writes src/img_watch_icons.c)
"""
import math
import pathlib

from PIL import Image, ImageDraw

SIZE = 44           # Pixels on screen (button icons)
APP_SIZE = 80       # App list and face icons, scaled down by the UI
SS = 8              # Supersampling
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "img_watch_icons.c"


def canvas(size=SIZE):
    img = Image.new("L", (size * SS, size * SS), 0)
    return img, ImageDraw.Draw(img)


def disc(d, x, y, r):
    d.ellipse((x - r, y - r, x + r, y + r), fill=255)


def reset_icon():
    """One clockwise arrow around a circle, its head just before the gap."""
    img, d = canvas()
    s = SIZE * SS
    cx = cy = s / 2
    w = 0.13 * s                    # Stroke
    r = 0.40 * s - w / 2            # Stroke centre line
    start, end = 8, 312             # Degrees, clockwise from 3 o'clock
    d.arc((cx - r - w / 2, cy - r - w / 2, cx + r + w / 2, cy + r + w / 2),
          start, end, fill=255, width=int(w))
    a = math.radians(start)
    disc(d, cx + r * math.cos(a), cy + r * math.sin(a), w / 2)      # Round tail
    a = math.radians(end)
    px, py = cx + r * math.cos(a), cy + r * math.sin(a)
    nx, ny = math.cos(a), math.sin(a)                               # Outward
    tx, ty = -math.sin(a), math.cos(a)                              # Clockwise
    head = 1.25 * w
    d.polygon([(px + nx * head, py + ny * head),
               (px - nx * head, py - ny * head),
               (px + tx * head * 1.5, py + ty * head * 1.5)], fill=255)
    return img


def flag_icon():
    """A pennant on a pole, for "Lap"."""
    img, d = canvas()
    s = SIZE * SS
    w = 0.11 * s
    x = 0.27 * s
    top, bottom = 0.12 * s, 0.88 * s
    d.rectangle((x - w / 2, top, x + w / 2, bottom), fill=255)
    disc(d, x, top, w / 2)
    disc(d, x, bottom, w / 2)
    d.polygon([(x, top), (0.84 * s, 0.32 * s), (x, 0.56 * s)], fill=255)
    return img


def stopwatch_icon():
    """A round watch with a crown on top and one hand, for the Stopwatch app."""
    img, d = canvas(APP_SIZE)
    s = APP_SIZE * SS
    cx, cy = s / 2, s * 0.56
    w = 0.09 * s
    r = 0.36 * s
    d.ellipse((cx - r, cy - r, cx + r, cy + r), outline=255, width=int(w))
    d.rounded_rectangle((cx - 0.08 * s, 0.04 * s, cx + 0.08 * s, 0.13 * s), radius=0.02 * s, fill=255)
    d.rectangle((cx - w / 3, 0.12 * s, cx + w / 3, cy - r + w / 2), fill=255)
    a = math.radians(-60)                                           # Hand at about 2 o'clock
    hx, hy = cx + 0.24 * s * math.cos(a), cy + 0.24 * s * math.sin(a)
    d.line((cx, cy, hx, hy), fill=255, width=int(w * 0.8))
    disc(d, cx, cy, w * 0.75)
    disc(d, hx, hy, w * 0.4)
    return img


def timer_icon():
    """An hourglass, for the Timer app."""
    img, d = canvas(APP_SIZE)
    s = APP_SIZE * SS
    w = 0.08 * s
    left, right = 0.22 * s, 0.78 * s
    top, bottom = 0.10 * s, 0.90 * s
    d.rounded_rectangle((left - 0.04 * s, top - w / 2, right + 0.04 * s, top + w / 2), radius=w / 2, fill=255)
    d.rounded_rectangle((left - 0.04 * s, bottom - w / 2, right + 0.04 * s, bottom + w / 2), radius=w / 2, fill=255)
    mid = s / 2
    neck = 0.05 * s
    glass = [(left, top), (right, top), (mid + neck, mid), (right, bottom), (left, bottom), (mid - neck, mid)]
    d.line(glass + [glass[0]], fill=255, width=int(w * 0.7), joint="curve")
    d.polygon([(left + 0.10 * s, top + 0.08 * s), (right - 0.10 * s, top + 0.08 * s), (mid, mid - 0.06 * s)],
              fill=255)                                             # Sand on top
    d.polygon([(mid, bottom - 0.22 * s), (right - 0.06 * s, bottom - 0.05 * s),
               (left + 0.06 * s, bottom - 0.05 * s)], fill=255)     # And below
    return img


def c_array(name, img):
    size = img.size[0] // SS
    img = img.resize((size, size), Image.LANCZOS)
    data = img.tobytes()
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return (
        "static const uint8_t %s_map[] = {\n%s\n};\n\n"
        "const lv_image_dsc_t %s = {\n"
        "    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
        "    .header.cf = LV_COLOR_FORMAT_A8,\n"
        "    .header.w = %d,\n"
        "    .header.h = %d,\n"
        "    .header.stride = %d,\n"
        "    .data_size = sizeof(%s_map),\n"
        "    .data = %s_map,\n"
        "};\n" % (name, "\n".join(rows), name, size, size, size, name, name)
    )


def main():
    body = [
        "/* Generated by tools/gen_watch_icons.py; edit that instead. */",
        "#include <lvgl.h>",
        "",
        c_array("img_watch_reset", reset_icon()),
        c_array("img_watch_lap", flag_icon()),
        c_array("img_watch_stopwatch", stopwatch_icon()),
        c_array("img_watch_timer", timer_icon()),
    ]
    OUT.write_text("\n".join(body))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
